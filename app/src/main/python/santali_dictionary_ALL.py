def normalize_hindi(text):
    text = str(text or '').replace('।', '').strip()
    text = ' '.join(text.split())
    return text.lower()

def lookup_santali(text):
    raw = str(text or '').strip()
    if not raw:
        return None

    # Exact lookup first.
    if raw in SANTALI_DICTIONARY:
        return SANTALI_DICTIONARY[raw]

    # Normalized lookup handles punctuation/spacing.
    key = normalize_hindi(raw)
    return SANTALI_DICTIONARY.get(key)

